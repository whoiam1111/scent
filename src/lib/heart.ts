// 체크한 문항의 키: "영역|문장"
export const itemKey = (area: Area, text: string) => `${area}|${text}`;

// 한 영역의 문항을 유형별로 번갈아 섞는다 — 같은 유형 문장이 몰려 보이지 않게, 겹치는 문장은 한 번만
export function areaItems(area: Area): string[] {
  const out = new Set<string>();
  const longest = Math.max(...heartTypes.map((h) => h.items[area].length));
  for (let i = 0; i < longest; i++) for (const h of heartTypes) if (h.items[area][i]) out.add(h.items[area][i]);
  return [...out];
}

export type HeartScore = { type: HeartType; picked: string[]; total: number; ratio: number };

export function scoreHeart(picks: Set<string>): HeartScore[] {
  return heartTypes
    .map((type) => {
      const all = AREAS.flatMap((a) => type.items[a].map((x) => [a, x] as const));
      const picked = all.filter(([a, x]) => picks.has(itemKey(a, x))).map(([, x]) => x);
      return { type, picked, total: all.length, ratio: picked.length / all.length };
    })
    .sort((a, b) => b.ratio - a.ratio || b.picked.length - a.picked.length || a.type.id - b.type.id);
}

// 한 화면에 10개 안팎만 — 영역마다 고르게 나눠 페이지를 만든다 (예: 65개 → 10·11·11·11·11·11)
export const PAGE_SIZE = 10;
export type HeartPage = { area: Area; part: number; parts: number; items: string[] };

export const heartPages: HeartPage[] = AREAS.flatMap((area) => {
  const all = areaItems(area);
  const parts = Math.max(1, Math.floor(all.length / PAGE_SIZE));
  return Array.from({ length: parts }, (_, i) => ({
    area,
    part: i + 1,
    parts,
    items: all.slice(Math.round((i * all.length) / parts), Math.round(((i + 1) * all.length) / parts)),
  }));
});
